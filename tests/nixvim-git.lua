local root = assert(vim.env.NIXVIM_TEST_DIR) .. "/git fixture"
vim.fn.mkdir(root .. "/undo", "p")
vim.o.undodir = root .. "/undo"
vim.fn.mkdir(root, "p")
local function git(...)
  local args = { "git", "-C", root }
  vim.list_extend(args, { ... })
  local result = vim.system(args, { text = true }):wait()
  assert(result.code == 0, table.concat(args, " ") .. ": " .. (result.stderr or ""))
  return result.stdout
end
git("init", "-q")
git("config", "user.name", "Fixture")
git("config", "user.email", "fixture@example.invalid")
local path = root .. "/file.txt"
vim.fn.writefile({ "one", "two", "three" }, path)
git("add", "file.txt")
git("commit", "-qm", "initial")
vim.fn.writefile({ "one", "changed", "three" }, path)
vim.fn.chdir(root)
vim.cmd("edit " .. vim.fn.fnameescape(path))
assert(vim.fn.exists(":DiffviewOpen") == 2 and vim.fn.exists(":Octo") == 2, "Git plugin command missing")
assert(vim.fn.executable("gh") == 1, "GitHub CLI missing")
assert(vim.fn.maparg(vim.g.mapleader .. "hs", "v") ~= "", "visual stage mapping missing")
assert(vim.wait(10000, function()
  local hunks = require("gitsigns").get_hunks()
  return hunks and #hunks > 0
end, 50), "Gitsigns did not discover the changed hunk")
vim.api.nvim_win_set_cursor(0, { 2, 0 })
vim.cmd("Gitsigns stage_hunk")
assert(vim.wait(10000, function() return git("diff", "--cached", "--", "file.txt"):find("+changed", 1, true) ~= nil end, 50), "Gitsigns failed to stage hunk")
vim.cmd("DiffviewOpen")
assert(vim.wait(10000, function()
  local view = require("diffview.lib").get_current_view()
  return view and view.cur_entry and view.cur_entry.opened
end, 50), "Diffview did not open")
vim.cmd("DiffviewClose")
local first_commit = git("rev-parse", "HEAD"):gsub("\n$", "")
vim.api.nvim_cmd({ cmd = "DiffviewOpen", args = { first_commit .. "^!" } }, {})
assert(vim.wait(10000, function()
  local view = require("diffview.lib").get_current_view()
  return view and view.files and #view.files.working > 0 and view.cur_entry and view.cur_entry.opened
end, 50), "Diffview could not show the initial commit")
vim.cmd("DiffviewClose")
git("commit", "-qm", "base for conflict")
git("switch", "-qc", "other")
vim.fn.writefile({ "one", "other branch", "three" }, path)
git("commit", "-qam", "other side")
git("switch", "-q", "-")
vim.fn.writefile({ "one", "current branch", "three" }, path)
git("commit", "-qam", "current side")
local merge = vim.system({ "git", "-C", root, "merge", "other" }, { text = true }):wait()
assert(merge.code ~= 0, "fixture did not produce a merge conflict")
vim.cmd("checktime")
vim.cmd("DiffviewOpen")
assert(vim.wait(10000, function()
  local view = require("diffview.lib").get_current_view()
  return view and view.files and #view.files.conflicting > 0 and view.cur_entry and view.cur_entry.opened
end, 50), "Diffview did not expose the merge conflict")
vim.cmd("DiffviewClose")
